/** Regenerate src/abi.generated.ts from the Foundry build (run `forge build` in contracts/ first):  pnpm --filter @sublevel/chain abi */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
let ts = "// GENERATED by scripts/abi.ts from contracts/out — do not edit.\n";
for (const name of ["Cards", "Armory", "Arena", "Ladder"]) {
  const j = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8"));
  ts += `\nexport const ${name.toLowerCase()}Abi = ${JSON.stringify(j.abi)} as const;\n`;
}
writeFileSync(resolve(here, "../src/abi.generated.ts"), ts);
console.log("wrote src/abi.generated.ts");

// The one-transaction deployer: creation code + ABI, so a wallet can deploy everything from the /deploy page (no CLI, no key sharing).
const b = JSON.parse(readFileSync(resolve(out, "Bootstrap.sol/Bootstrap.json"), "utf8"));
const bs = [
  "// GENERATED by scripts/abi.ts from contracts/out/Bootstrap — do not edit. Rebuild with `forge build` then `pnpm --filter @sublevel/chain abi`.",
  `export const bootstrapAbi = ${JSON.stringify(b.abi)} as const;`,
  `export const bootstrapBytecode = "0x${String(b.bytecode.object).replace(/^0x/, "")}" as const;`,
  "",
].join("\n");
writeFileSync(resolve(here, "../src/bootstrap.generated.ts"), bs);
console.log("wrote src/bootstrap.generated.ts", Math.round(bs.length / 1024), "KB");
