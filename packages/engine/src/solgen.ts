/**
 * Generate contracts/src/RulebookV1.sol from rulebook.ts — the contract's numbers can never drift from the engine's.
 *   pnpm --filter @sublevel/engine solgen
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ATTACKS, FULL, GRIT_CAP, LITE, RULEBOOK_VERSION, SPREADS, STYLE_NAMES, TRICKS, TRICK_COST, V1_RULES } from "./rulebook";
import { PRESETS } from "./builds";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/src/RulebookV1.sol");

const hex = (bytes: number[]) => bytes.map((b) => b.toString(16).padStart(2, "0")).join("");
const atk = hex(ATTACKS.flatMap((a) => [a.style, a.cost, a.dmg, a.tag]));
const spr = hex(SPREADS.flatMap((s) => [s.hp, s.retreat]));
const fmt = (f: typeof LITE) => `Format(${f.id}, ${f.fighters}, ${f.tricks}, ${f.koTarget}, ${f.turnCap}, ${f.startGrit}, ${f.hpPct}, ${f.hidden})`;

const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// ⚠ GENERATED by packages/engine/src/solgen.ts from rulebook.ts — do not edit by hand.
// Rulebook ${RULEBOOK_VERSION}: guard triangle + free unpunished Switch are HARD-WIRED (no flags on-chain).

/// @notice Numbers for Rulebook ${RULEBOOK_VERSION}. Cards store ids; these tables give them meaning.
library RulebookV1 {
    string internal constant VERSION = "${RULEBOOK_VERSION}";

    uint8 internal constant GRIT_CAP = ${GRIT_CAP};
    uint8 internal constant TRICK_COST = ${TRICK_COST};
    uint8 internal constant ATTACK_COUNT = ${ATTACKS.length};
    uint8 internal constant SPREAD_COUNT = ${SPREADS.length};
    uint8 internal constant TRICK_COUNT = ${TRICKS.length};

    /// attack tag ids
    uint8 internal constant TAG_PLAIN = 0;
    uint8 internal constant TAG_GRAPPLE = 1;
    uint8 internal constant TAG_COUNTER = 2;
    uint8 internal constant TAG_PIERCE = 3;

    struct Format {
        uint8 id;
        uint8 fighters;
        uint8 tricks;
        uint8 koTarget;
        uint8 turnCap;
        uint8 startGrit;
        uint8 hpPct;
        bool hidden;
    }

    // ${ATTACKS.length} attacks × 4 bytes: style, cost, dmg, tag
    bytes internal constant ATTACKS = hex"${atk}";
    // ${SPREADS.length} spreads × 2 bytes: hp, retreat
    bytes internal constant SPREADS = hex"${spr}";

    function attack(uint8 id) internal pure returns (uint8 style, uint8 cost, uint8 dmg, uint8 tag) {
        require(id < ATTACK_COUNT, "attack id");
        uint256 o = uint256(id) * 4;
        return (uint8(ATTACKS[o]), uint8(ATTACKS[o + 1]), uint8(ATTACKS[o + 2]), uint8(ATTACKS[o + 3]));
    }

    function spread(uint8 id) internal pure returns (uint8 hp, uint8 retreat) {
        require(id < SPREAD_COUNT, "spread id");
        uint256 o = uint256(id) * 2;
        return (uint8(SPREADS[o]), uint8(SPREADS[o + 1]));
    }

    function isHeavy(uint8 cost) internal pure returns (bool) {
        return cost >= 3;
    }

    /// @dev A fighter carries exactly ONE light and ONE heavy attack, both of its style.
    function isLegalBuild(uint8 style, uint8 atk0, uint8 atk1, uint8 spreadId) internal pure returns (bool) {
        if (style > 2 || atk0 >= ATTACK_COUNT || atk1 >= ATTACK_COUNT || atk0 == atk1 || spreadId >= SPREAD_COUNT) return false;
        (uint8 s0, uint8 c0, , ) = attack(atk0);
        (uint8 s1, uint8 c1, , ) = attack(atk1);
        if (s0 != style || s1 != style) return false;
        return isHeavy(c0) != isHeavy(c1);
    }

    function format(uint8 id) internal pure returns (Format memory) {
        if (id == 0) return ${fmt(LITE)};
        if (id == 1) return ${fmt(FULL)};
        revert("format id");
    }

    /// v1 rule switches (informational; the engine hard-wires them)
    bool internal constant SWITCH_REFUND_IF_UNATTACKED = ${V1_RULES.switchRefundIfUnattacked};
    bool internal constant GUARD_TRIANGLE = ${V1_RULES.guardTriangle};
    bool internal constant BRACE_GAIN_IF_UNATTACKED = ${V1_RULES.braceGainIfUnattacked};
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sol);
console.log("wrote", out);

/* ---------------- names + starter presets (metadata & the free starter pool) ---------------- */
const namesOut = resolve(here, "../../../contracts/src/RulebookNames.sol");
const q = (n: string) => n.replace(/"/g, '\\"');
const chain = (arr: string[]) =>
  arr.map((n, i) => `        ${i === 0 ? "if" : "else if"} (id == ${i}) return "${q(n)}";`).join("\n") + `\n        return "?";`;
const presetChain = PRESETS.map(
  (p, i) => `        ${i === 0 ? "if" : "else if"} (id == ${i}) return ("${q(p.name)}", ${p.build.style}, ${p.build.attackIds[0]}, ${p.build.attackIds[1]}, ${p.build.spread});`,
).join("\n");

const namesSol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// ⚠ GENERATED by packages/engine/src/solgen.ts from rulebook.ts / builds.ts — do not edit by hand.

/// @notice Human-readable names + the 12 starter presets (used for tokenURI metadata and the free starter pool).
library RulebookNames {
    function styleName(uint8 id) internal pure returns (string memory) {
${chain([...STYLE_NAMES])}
    }

    function attackName(uint8 id) internal pure returns (string memory) {
${chain(ATTACKS.map((a) => a.name))}
    }

    function spreadName(uint8 id) internal pure returns (string memory) {
${chain(SPREADS.map((x) => x.name))}
    }

    function trickName(uint8 id) internal pure returns (string memory) {
${chain(TRICKS.map((t) => t.name))}
    }

    uint8 internal constant PRESET_COUNT = ${PRESETS.length};

    /// @dev starter fighter presets: (name, style, atk0, atk1, spread)
    function preset(uint8 id) internal pure returns (string memory name, uint8 style, uint8 atk0, uint8 atk1, uint8 spreadId) {
${presetChain}
        revert("preset id");
    }
}
`;
writeFileSync(namesOut, namesSol);
console.log("wrote", namesOut);
