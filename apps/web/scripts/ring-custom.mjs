import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const logs = [];
page.on("console", (m) => m.type() === "error" && logs.push(m.text()));
page.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
await page.addInitScript(() => localStorage.setItem("sublevel.customs.v1", JSON.stringify([{ id: "abc1234", name: "Dutch Marlene", style: 2, attackIds: [14, 16], spread: 2 }])));
await page.goto("http://localhost:3000/?r=2d", { waitUntil: "networkidle" });
await page.getByText("ENTER THE BASEMENT").click();
await page.waitForTimeout(600);
await page.keyboard.press("Escape");
await page.getByText(/^YOURS \(1\)/).click();
await page.locator("button", { hasText: "Counter · Flurry" }).first().click();
await page.getByText("TO THE RING").click();
await page.waitForTimeout(2500);
console.log("custom fighter in the ring:", await page.getByText("DUTCH MARLENE").first().isVisible().catch(() => false));
await page.screenshot({ path: "shots/ring-custom.png" });
console.log(logs.join("\n") || "(no errors)");
await browser.close();
